const DICTIONARIES = { en: EN, pt: PT };

export function useDesignT() {
  const { locale } = useTranslation();

  return useCallback(
    (text: string, vars?: Vars) => {
      const dictionary = DICTIONARIES[locale as keyof typeof DICTIONARIES];
      let translated = dictionary?.[text] ?? text;
      if (vars) {
        for (const [key, value] of Object.entries(vars)) {
          translated = translated.replaceAll(`{{${key}}}`, String(value));
        }
      }
      return translated;
    },
    [locale],
  );
}

export function useDesignLocale() {
  const { locale } = useTranslation();
  if (locale === 'en') return 'en-US';
  if (locale === 'pt') return 'pt-BR';
  return 'es-CO';
}
